def p(text, bold=False, italic=False, align=None, indent=True):
    para = doc.add_paragraph()
    r = para.add_run(text)
    r.bold, r.italic = bold, italic
    if indent:
        para.paragraph_format.first_line_indent = Cm(1.25)
    para.alignment = align if align is not None else WD_ALIGN_PARAGRAPH.JUSTIFY
    return para


def bullets(items):
    for it in items:
        para = doc.add_paragraph(style="List Bullet")
        para.add_run(it)
        para.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY


def table(header, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    for i, h in enumerate(header):
        c = t.rows[0].cells[i]
        c.text = ""
        c.paragraphs[0].add_run(h).bold = True
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = str(v)
    for row in t.rows:
        for c in row.cells:
            for para in c.paragraphs:
                para.paragraph_format.line_spacing = 1.0
                for r in para.runs:
                    r.font.size = Pt(12)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()


def shot(n, desc):
    """Рамка-заглушка для скріншота з описом того, що саме треба вставити."""
    t = doc.add_table(rows=1, cols=1)
    t.style = "Table Grid"
    c = t.rows[0].cells[0]
    c.text = ""
    r = c.paragraphs[0].add_run(f"[МІСЦЕ ДЛЯ СКРІНШОТА {n}]\n\n{desc}\n\n")
    r.italic = True
    c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
    c.paragraphs[0].paragraph_format.line_spacing = 1.0
    t.rows[0].height = Cm(6)
    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.add_run(f"Рисунок {n} – {desc.split('.')[0]}").italic = True


