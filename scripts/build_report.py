fig_counter = 1


def p(text: str, bold: bool = False, italic: bool = False, align=None, indent: bool = True):
    para = doc.add_paragraph()
    r = para.add_run(text)
    r.bold, r.italic = bold, italic
    if indent:
        para.paragraph_format.first_line_indent = Cm(1.25)
    para.alignment = align if align is not None else WD_ALIGN_PARAGRAPH.JUSTIFY
    return para


def bullets(items: list[str]):
    for it in items:
        para = doc.add_paragraph(style="List Bullet")
        para.add_run(it)
        para.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY


def table(header: list[str], rows: list[list[str]], widths: list[float] | None = None):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    for i, h in enumerate(header):
        c = t.rows[0].cells[i]
        c.text = ""
        c.paragraphs[0].add_run(h).bold = True
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = str(v)
    for row in t.rows:
        for c in row.cells:
            for para in c.paragraphs:
                para.paragraph_format.line_spacing = 1.0
                for r in para.runs:
                    r.font.size = Pt(11.5)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()


def embed_plot(filename: str, caption_text: str, width_cm: float = 13.5):
    """Вставляє реальний графік PNG у звіт з нумерованим підписом."""
    global fig_counter
    path = os.path.join(FIGURES_DIR, filename)
    para = doc.add_paragraph()
    para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    para.paragraph_format.space_before = Pt(6)
    para.paragraph_format.space_after = Pt(2)
    run = para.add_run()
    run.add_picture(path, width=Cm(width_cm))

    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.space_after = Pt(8)
    cap_run = cap.add_run(f"Рисунок {fig_counter} – {caption_text}")
    cap_run.italic = True
    cap_run.font.size = Pt(12)
    fig_counter += 1


def shot(desc: str):
    """Рамка-заглушка для скріншота інтерфейсу Streamlit, який вставляє користувач."""
    global fig_counter
    t = doc.add_table(rows=1, cols=1)
    t.style = "Table Grid"
    c = t.rows[0].cells[0]
    c.text = ""
    r = c.paragraphs[0].add_run(f"[МІСЦЕ ДЛЯ СКРІНШОТА ІНТЕРФЕЙСУ №{fig_counter}]\n\n{desc}\n")
    r.italic = True
    c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
    c.paragraphs[0].paragraph_format.line_spacing = 1.1
    t.rows[0].height = Cm(5.0)

    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.space_after = Pt(8)
    cap_run = cap.add_run(f"Рисунок {fig_counter} – {desc.split('.')[0]}")
    cap_run.italic = True
    cap_run.font.size = Pt(12)
    fig_counter += 1


